"""Audit title capitalisation across report section headings.

Reports generated by different collectors sometimes end up with a mix of
Title Case, sentence case and ALL CAPS headings.  The audit groups headings
by style so a template owner can pick one convention deliberately.
"""

import logging
import re
from typing import Dict, List

LOG = logging.getLogger(__name__)

WORD_PATTERN = re.compile(r"[A-Za-z]+")


def classify_heading(heading: str) -> str:
    """Classify a heading as ``upper``, ``title``, ``sentence`` or ``mixed``."""
    words = WORD_PATTERN.findall(heading.strip())
    if not words:
        return "empty"
    if all(word.isupper() for word in words if len(word) > 1):
        return "upper"
    if all(word[0].isupper() for word in words):
        return "title"
    if words[0][0].isupper() and all(not word[0].isupper() for word in words[1:]):
        return "sentence"
    return "mixed"


def audit_headings(headings: List[str]) -> Dict[str, List[str]]:
    """Group headings by capitalisation style in input order."""
    buckets: Dict[str, List[str]] = {}
    for heading in headings:
        style = classify_heading(heading)
        buckets.setdefault(style, []).append(heading)
    if len(buckets) > 1:
        LOG.info("headings use %d different capitalisation styles", len(buckets))
    return buckets


def dominant_style(headings: List[str]) -> str:
    """Return the most common style, defaulting to ``empty``."""
    buckets = audit_headings(headings)
    if not buckets:
        return "empty"
    return max(buckets, key=lambda style: len(buckets[style]))


__all__ = ["classify_heading", "audit_headings", "dominant_style"]
